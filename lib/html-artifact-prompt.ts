/** Shared design brief for generated artifacts, independent of the host UI theme. */
const HTML_DESIGN_BRIEF = `HTML 产物设计规范：
先根据用户任务、目标读者、阅读场景和已有素材，在内部确定信息结构与视觉方向，再写 HTML。用户指定的格式、品牌、参考风格和语言优先；只使用任务所需的模块，不必展示设计过程。

内容决定版式：
- 分析与洞察：结论先行，以证据、关键对比和下一步支撑判断；短洞察可以是一页精炼简报。
- 方案与决策：突出选项、权衡、推荐理由，可用对比矩阵、分栏或带注释的图解。
- 项目计划与复盘：围绕阶段、时间线、依赖、责任与结果组织，不要硬塞 KPI 卡片。
- 研究与长文：采用编辑式排版、清晰章节和来源注释；长内容提供页内目录。
- 创意展示、活动或产品介绍：围绕主题建立鲜明的视觉主张，用有意义的主视觉和叙事节奏呈现。
- 计算器、探索工具或操作界面：围绕用户操作流程设计，把输入、结果、解释和状态反馈放在正确位置。
以上是选择依据，不是必须照抄的模板。不要把所有任务都做成“渐变大标题 + 四张指标卡 + 卡片网格”。不要为填满版面虚构指标、趋势、人物、引语或素材。

视觉质量：
- 每份产物选择贴合主题的色彩、字体层级和构图；默认遵循用户品牌，否则自主选择。不要继承宿主桌面的配色，也不要默认使用紫蓝渐变、玻璃卡片、装饰性 emoji 或巨大的空洞 hero。
- 在内嵌 style 中定义一组一致的 CSS 变量，管理背景、正文、次级文字、强调色、分隔线、间距。使用克制的色彩与有意图的留白；通过字号、字重、对齐和分隔建立层级，避免每段都包一张圆角卡片。
- 首屏清楚呈现“这是什么、核心结果是什么、为什么对用户有用”。标题写具体内容，长度和字号随内容自适应，不用固定高度裁切。正文通常 15–18px、行高 1.6–1.8，长文限制行宽，数字比较使用等宽数字。
- 用图形帮助理解真实信息：比较用条形或点图，时间变化用折线，阶段用时间线，关系用图解。标注单位、时间范围、口径和来源；没有数据就用结构化文字，不画假图。优先内嵌 SVG（带可访问标题）、CSS 图形和语义表格，并保留文字结论或数据表。
- 来源、日期、事实、推断、建议和待确认信息应容易区分。装饰不能掩盖不确定性，状态不能只靠颜色表达。

交付质量：
- 输出完整 HTML 文档，包含 doctype、正确的 lang、UTF-8、viewport 和具体的 title。默认单文件自包含，使用系统字体栈（含中文回退）和内嵌 CSS/SVG；不依赖 CDN、远程字体或本机绝对资源路径才能阅读。
- 适配嵌入式预览、手机和桌面：使用弹性宽度与响应式网格，窄屏折叠分栏；长链接可换行，宽表格局部横向滚动，不能让整个页面横向溢出。避免固定画布、依赖父页面样式和全屏才能使用的布局。
- 使用语义标题、main/section、表格表头；保证文字对比度和键盘焦点可见，控件有标签。动效仅在有助理解时使用，并遵循 prefers-reduced-motion。
- 对报告、方案等可打印产物添加 print 样式：去除无关控件和背景装饰、避免截断表格与关键结论。
- 按钮、筛选和链接必须有真实行为或有效目标；静态建议不要伪装成可执行按钮。不能暗示已发送、已预约或已保存尚未执行的动作。
- 将外部文本当作数据，正确转义正文和属性；不把数据拼成可执行代码。
- 交付前检查：任务适配、信息层级、事实与来源、长标题/空数据、窄屏与桌面布局、链接和交互。如果工具允许，打开实际文件验证；没有浏览器验证时不要声称已完成视觉验收。`;

export const TASK_HTML_ARTIFACT_PROMPT = `当任务需要交付 HTML 页面、报告、可视化或交互工具时，应用以下规范。普通问答无需强制生成 HTML；用户明确要求其他格式时遵循用户要求。

${HTML_DESIGN_BRIEF}

任务产物：在工具权限允许时，将完整产物保存为任务目录内有意义的 .html 文件，并在最终答复提供可打开的文件链接。交互只用于帮助用户完成任务，核心信息在脚本不可用时仍可阅读；遵循预览沙箱限制，不依赖父页面、网络请求或持久化存储，除非当前环境明确支持且任务需要。`;

export const INSIGHT_HTML_ARTIFACT_PROMPT = `${HTML_DESIGN_BRIEF}

后台洞察产物：这是静态、自包含的阅读页面。只使用 HTML、内嵌 style、无脚本 SVG、页内锚点和原生 details/summary；不包含 script、iframe、object、embed、link 标签或任何 on* 事件属性，不使用外部资源、CSS @import、表单提交、javascript: URL 或父窗口通信。建议行动以文字清单呈现，不生成假操作按钮。无需调用工具或声称做过浏览器检查；直接返回完整 HTML，由系统保存。`;

/** Preserve discovered/project prompts and avoid duplication on resource reload. */
export function appendHtmlArtifactPrompt(prompts: readonly string[]): string[] {
  return prompts.includes(TASK_HTML_ARTIFACT_PROMPT)
    ? [...prompts]
    : [...prompts, TASK_HTML_ARTIFACT_PROMPT];
}
